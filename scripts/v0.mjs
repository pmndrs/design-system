/** The pmndrs theme as a CSS file for Open in v0, which does not read cssVars. */
import { mtbColors } from 'material-theme-builder/tailwind'
import { pmndrsMtb } from '../registry/md3-base/md3.ts'
import { hostedUrl } from './hosted-registry.url.ts'
import { sansFont } from './packages.mjs'
import { readRemap, tailwindColors } from './remap.mjs'

/**
 * Theme mappings and fonts layered on the palette registry dependency.
 *
 * @param {ReturnType<typeof import('./foundations.mjs').readFoundations>} foundations
 * @param {{ family: string, dependency: string }} mono
 */
export function v0GlobalsCss(foundations, mono) {
  const remap = readRemap()
  const sans = sansFont(foundations)
  const declarations = (entries) => entries.map(([name, value]) => `  ${name}: ${value};`).join('\n')
  const colors = {
    ...Object.fromEntries(
      Object.entries(mtbColors({ customColors: pmndrsMtb.customColors.map(({ name }) => name) }))
        .map(([name, value]) => [`--color-${name}`, value])
    ),
    ...Object.fromEntries(tailwindColors(remap)),
  }
  const radius = foundations.radius.scale.filter(({ formula }) => formula.includes('var(--radius)'))

  return `/* Generated by scripts/build.mjs: edit the theme sources instead. */
@import "tailwindcss";
@import "tw-animate-css";
@import "shadcn/tailwind.css";
@import "${sans.dependency}";
@import "${mono.dependency}";
@import "../src/assets/pmndrs.css";

@custom-variant dark (&:is(.dark *));

@theme inline {
${declarations([
  ['--font-sans', sans.family],
  ['--font-heading', 'var(--font-sans)'],
  ['--font-mono', mono.family],
  ...Object.entries(colors),
  ...radius.map(({ token, formula }) => [token, formula]),
])}
}

:root {
${declarations([
  ['--radius', foundations.radius.base],
  ...remap.map(({ name, role }) => [name, `var(${role})`]),
])}
}

.dark {
${declarations([
  ...remap.map(({ name, role }) => [name, `var(${role})`]),
])}
}

@layer base {
  * {
    @apply border-border outline-ring/50;
  }
  body {
    @apply bg-background text-foreground;
  }
  html {
    @apply font-sans;
  }
  code,
  kbd,
  samp,
  pre {
    @apply font-mono;
  }
}
`
}

/** A public registry item URL is all Open in v0 needs. */
export const v0Link = `https://v0.app/chat/api/open?${new URLSearchParams({ url: `${hostedUrl}v0.json`, title: 'pmndrs' })}`
